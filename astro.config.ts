import mdx from '@astrojs/mdx';
import sitemap from '@astrojs/sitemap';
import tailwindcss from '@tailwindcss/vite';
import { defineConfig, fontProviders } from 'astro/config';
import { IS_FIXTURE_BUILD, loadSiteConfig, resolveSiteUrl } from './src/config/load.ts';
import { cspDirectives } from './src/lib/csp.ts';

const site = loadSiteConfig();
const siteUrl = resolveSiteUrl(site);
const csp = cspDirectives(site);

/** Basic Latin + Latin-1 + common punctuation (the "latin" subset). */
const LATIN_RANGE =
  'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD';

// https://docs.astro.build/en/reference/configuration-reference/
export default defineConfig({
  site: siteUrl,
  trailingSlash: 'always',
  outDir: IS_FIXTURE_BUILD ? './dist-fixtures' : './dist',
  cacheDir: IS_FIXTURE_BUILD ? './node_modules/.astro-fixtures' : './node_modules/.astro',
  build: { format: 'directory', inlineStylesheets: 'auto' },
  prefetch: { prefetchAll: true, defaultStrategy: 'hover' },

  integrations: [
    mdx(),
    // Only public pages are ever built, so the sitemap cannot contain drafts.
    sitemap({ filter: (page) => !/\/404\/?$/.test(page) }),
  ],

  vite: { plugins: [tailwindcss()] },

  // Self-hosted variable fonts (OFL-1.1) from installed npm packages, with
  // metric-matched fallbacks generated by Astro to minimise layout shift.
  fonts: [
    {
      provider: fontProviders.local(),
      name: 'Mona Sans',
      cssVariable: '--font-mona',
      fallbacks: ['sans-serif'],
      options: {
        variants: [
          {
            src: ['@fontsource-variable/mona-sans/files/mona-sans-latin-wght-normal.woff2'],
            weight: '200 900',
            style: 'normal',
            unicodeRange: [LATIN_RANGE],
          },
        ],
      },
    },
    {
      provider: fontProviders.local(),
      name: 'Geist Mono',
      cssVariable: '--font-geist',
      fallbacks: ['monospace'],
      options: {
        variants: [
          {
            src: ['@fontsource-variable/geist-mono/files/geist-mono-latin-wght-normal.woff2'],
            weight: '100 900',
            style: 'normal',
            unicodeRange: [LATIN_RANGE],
          },
        ],
      },
    },
  ],

  // Prism emits CSS classes (styled in global.css) instead of inline styles,
  // which keeps code blocks compatible with the Content-Security-Policy.
  markdown: { syntaxHighlight: 'prism' },

  security: {
    csp: {
      directives: csp.directives as never,
      scriptDirective: { resources: csp.scriptResources },
      // <style>/<link> elements must be same-origin or hashed by Astro. Inline
      // style *attributes* (CSS custom properties such as --tone-h) are allowed.
      styleDirective: {
        resources: [
          { resource: "'self'", kind: 'element' },
          { resource: "'unsafe-inline'", kind: 'attribute' },
        ],
      },
    },
  },
});
